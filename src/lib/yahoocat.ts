export interface CatMatch {
  entry: CatEntry;
  score: number;
}

/** 商品名(重み3) / カテゴリ文字列(重み2) / 説明(重み1) からカテゴリ候補を採点。 */
export function matchCategory(name: string, category: string, desc: string): CatMatch[] {
  const n = name.toLowerCase();
  const c = category.toLowerCase();
  const d = desc.toLowerCase();
  const results: CatMatch[] = [];
  for (const entry of YAHOO_CATEGORIES) {
    let score = 0;
    for (const kw of entry.keywords) {
      const k = kw.toLowerCase();
      if (n.includes(k)) score += 3;
      if (c.includes(k)) score += 2;
      if (d.includes(k)) score += 1;
    }
    if (score > 0) results.push({ entry, score });
  }
  results.sort((a, b) => b.score - a.score);
  return results.slice(0, 4);
}
